/* draw one character cell (6x8 * scale) with fg/bg; lowercase maps to uppercase */
void lcd_char(int x, int y, char ch, int scale, uint16_t fg, uint16_t bg)
{
	if (ch >= 'a' && ch <= 'z')
		ch -= 32;
	if (ch < 0x20 || ch > 0x5f)
		ch = '?';
	const uint8_t *g = font5x7[ch - 0x20];
	int w = 6 * scale, h = 8 * scale;
	uint32_t pf = px(fg), pb = px(bg), saved;

	if (x + w > LCD_W || y + h > LCD_H)
		return;
	lcd_lock();
	lcd_window(x, y, x + w - 1, y + h - 1);
	saved = CMU_CTL;
	CMU_CTL = (saved & 0xfffffeccu) | 1;
	LCDC_CTL = (LCDC_CTL & 0xe7cfff37u) | 0x40;
	for (int row = 0; row < h; row++) {
		int r = row / scale;
		for (int col = 0; col < w; col++) {
			int c = col / scale;
			LCDC_FIFO = (c < 5 && r < 7 && (g[c] >> r & 1)) ? pf : pb;
			(void)LCDC_CTL; /* pace the FIFO */
		}
	}
	CMU_CTL = saved;
	lcd_unlock();
}

void lcd_text(int x, int y, const char *s, int scale, uint16_t fg, uint16_t bg)
{
	for (; *s; s++, x += 6 * scale)
		lcd_char(x, y, *s, scale, fg, bg);
}
